prj_status_t prj_w25q_spi_init (void)
{
    esp_err_t err;
    gpio_reset_pin( CONFIG_PIN_NUM_CS );
    gpio_set_direction( CONFIG_PIN_NUM_CS, GPIO_MODE_OUTPUT );
    gpio_set_level( CONFIG_PIN_NUM_CS, 0 );

    return PRJ_SUCCESS;
}
